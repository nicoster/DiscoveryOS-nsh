import { expect, test } from "nsh/test";
import { Gb18030 } from "discoveryos/native";
import { formEncodeGb, pageTitle } from "./encoding";

test("decodes GB18030 bytes", () => {
  expect(Gb18030.decode(new Uint8Array([0xd6, 0xd0]))).toBe("中");
});

test("form-encodes values as GB18030 percent escapes", () => {
  // "中" is D6 D0 in GB18030; a space becomes %20.
  expect(formEncodeGb("中 a")).toBe("%D6%D0%20a");
});

test("reads the title of a GB18030 page", () => {
  // A Discuz-style page as GB18030 bytes: `<title>中文论坛 - 回帖测试</title>`.
  const bytes = new Uint8Array([0x3c, 0x68, 0x74, 0x6d, 0x6c, 0x3e, 0x3c, 0x68, 0x65, 0x61, 0x64, 0x3e, 0x3c, 0x74, 0x69, 0x74, 0x6c, 0x65, 0x3e, 0xd6, 0xd0, 0xce, 0xc4, 0xc2, 0xdb, 0xcc, 0xb3, 0x20, 0x2d, 0x20, 0xbb, 0xd8, 0xcc, 0xfb, 0xb2, 0xe2, 0xca, 0xd4, 0x3c, 0x2f, 0x74, 0x69, 0x74, 0x6c, 0x65, 0x3e, 0x3c, 0x2f, 0x68, 0x65, 0x61, 0x64, 0x3e, 0x3c, 0x2f, 0x68, 0x74, 0x6d, 0x6c, 0x3e]);
  expect(pageTitle(Gb18030.decode(bytes))).toBe("中文论坛 - 回帖测试");
});
